import { useState, useEffect } from 'react';
import { getTodos, createTodo, updateTodo, deleteTodo } from '../api';

export const useTodos = () => {
	// Состояние для хранения массива всех задач, полученных с сервера
	const [todos, setTodos] = useState([]);
	// Состояние для индикатора загрузки данных (true = идёт загрузка, false = загрузка завершена)
	const [isLoading, setIsLoading] = useState(false);
	// Состояние для хранения текста ошибки, если при загрузке данных что-то пошло не так
	const [error, setError] = useState(null);

	// useEffect с пустым массивом зависимостей [] выполняется только один раз при первом рендере компонента
	useEffect(() => {
		// Асинхронная функция для загрузки задач с сервера
		const fetchTodos = async () => {
			try {
				// Устанавливаем флаг загрузки в true перед началом запроса
				setIsLoading(true);
				// Вызываем API-функцию getTodos(), которая делает fetch-запрос к серверу
				// await ждёт, пока запрос выполнится и вернёт массив задач
				const loadedTodos = await getTodos();
				// Сохраняем полученный массив задач в состояние todos
				setTodos(loadedTodos);
			} catch (err) {
				// Если в процессе запроса произошла ошибка, сохраняем её текст в состояние error
				setError(err.message);
			} finally {
				// В любом случае (успех или ошибка) выключаем индикатор загрузки
				setIsLoading(false);
			}
		};

		// Вызываем функцию загрузки задач
		fetchTodos();
	}, []); // Пустой массив означает, что эффект запустится только один раз при монтировании компонента

	// Функция для создания новой задачи на сервере
	const handleCreateTodo = async (todoData) => {
		// async - функция асинхронная, т.к. работает с сетью (API запрос)
		// todoData - объект с данными новой задачи, например { title: "Купить молоко", completed: false }

		try {
			// Блок try-catch для обработки ошибок сети/сервера

			// 1. Отправляем POST запрос на сервер: /todos
			// createTodo(todoData) - функция из todosApi.js
			// await - ждём ответа сервера (новый объект задачи с проставленным id)
			const createdTodo = await createTodo(todoData);

			// 2. Обновляем локальное состояние todos
			// setTodos с функциональным обновлением (prev => ...) - получает ТЕКУЩИЙ массив
			// prev - предыдущее значение состояния todos (актуальный массив задач)
			setTodos((prev) => [
				// Создаём НОВЫЙ массив:
				...prev, // Сначала добавляем все предыдущие задачи (распаковываем массив prev)
				createdTodo, // Затем добавляем в конец только что созданную задачу с сервера
			]);

			// 3. Возвращаем созданную задачу наружу (на случай, если вызывающий код захочет её использовать)
			return createdTodo;
		} catch (err) {
			// Если createTodo выбросил ошибку (сервер недоступен, 404, 500...)
			// err содержит информацию: тип ошибки, текст, статус HTTP
			console.error('Ошибка при добавлении задачи:', err);
			// Логируем в консоль для отладки, НЕ ломает приложение
			// Пробрасываем ошибку дальше, чтобы вызывающий код мог её обработать
			throw err;
		}
	};

	// Функция для обновления задачи по ID. Принимает ID задачи и объект с изменениями (например, { title: "новый текст" })
	const handleUpdateTodo = async (id, updates) => {
		// async - функция асинхронная, т.к. работает с сетью (API запрос)
		// id - числовой ID задачи (например, 1, 2, 3...)
		// updates - объект с полями для изменения: { title: "...", completed: true }

		try {
			// Блок try-catch для обработки ошибок сети/сервера

			// 1. Отправляем PATCH запрос на сервер: /todos/:id
			// updateTodo(id, updates) - функция из todosApi.js
			// await - ждём ответа сервера (новый объект задачи с обновлёнными данными)
			const updatedTodo = await updateTodo(id, updates);

			// 2. Обновляем локальное состояние todos
			// setTodos с функциональным обновлением (prev => ...) - получает ТЕКУЩИЙ массив
			// prev - предыдущее значение состояния todos (актуальный массив задач)
			setTodos(
				(prev) =>
					// map проходит по КАЖДОЙ задаче в массиве и возвращает НОВЫЙ массив
					prev.map((todo) =>
						// Проверяем: если id текущей задачи (todo.id) === id обновляемой задачи
						todo.id === id
							? // ДА: заменяем задачу на updatedTodo (с сервера, с изменениями)
								updatedTodo
							: // НЕТ: оставляем задачу без изменений
								todo,
					), // map возвращает новый массив с одной заменённой задачей
			);

			// 3. Возвращаем обновлённую задачу наружу
			return updatedTodo;
		} catch (err) {
			// Если updateTodo выбросил ошибку (сервер недоступен, 404, 500...)
			// err содержит информацию: тип ошибки, текст, статус HTTP
			console.error('Ошибка редактирования:', err);
			// Логируем в консоль для отладки, НЕ ломает приложение
			// Пробрасываем ошибку дальше
			throw err;
		}
	};

	// Функция для удаления задачи по ID. Принимает ID задачи, которую нужно удалить
	const handleDeleteTodo = async (id) => {
		// async - функция асинхронная, т.к. работает с сетью (API запрос)
		// id - числовой ID задачи, которую нужно удалить

		try {
			// Блок try-catch для обработки ошибок сети/сервера

			// 1. Отправляем DELETE запрос на сервер: /todos/:id
			// deleteTodo(id) - функция из todosApi.js
			// await - ждём, пока запрос завершится (сервер удалит задачу)
			await deleteTodo(id);

			// 2. Если ошибок не было, обновляем локальное состояние
			// setTodos с функциональным обновлением (prev => ...) - получает ТЕКУЩИЙ массив
			// prev - предыдущее значение состояния todos (актуальный массив задач)
			setTodos(
				(prev) =>
					// filter проходит по КАЖДОЙ задаче в массиве и возвращает НОВЫЙ массив
					// только с теми задачами, для которых коллбэк вернул true
					prev.filter(
						(todo) =>
							// Проверяем: если id текущей задачи (todo.id) НЕ РАВЕН id удаляемой задачи
							todo.id !== id, // то оставляем эту задачу в новом массиве (true)
						// если id совпадает, то задача исключается из массива (false)
					), // filter возвращает новый массив БЕЗ удалённой задачи
			);
		} catch (err) {
			// Если deleteTodo выбросил ошибку (сервер недоступен, 404, 500...)
			// err содержит информацию: тип ошибки, текст, статус HTTP
			console.error('Ошибка при удалении задачи:', err);
			// Логируем в консоль для отладки, НЕ ломает приложение
			// Пробрасываем ошибку дальше
			throw err;
		}
	};

	// Функция для переключения статуса "выполнено" у задачи. Принимает ID задачи и новое значение completed (true или false)
	const handleToggleCompleted = async (id, newCompleted) => {
		// async - функция асинхронная, т.к. работает с сетью (API запрос)
		// id - числовой ID задачи, у которой нужно переключить статус
		// newCompleted - новое значение для поля completed (true = задача выполнена, false = не выполнена)

		try {
			// Блок try-catch для обработки ошибок сети/сервера

			// 1. Отправляем PATCH запрос на сервер: /todos/:id
			// Передаём только поле completed с новым значением
			// updateTodo(id, { completed: newCompleted }) - функция из todosApi.js
			// await - ждём ответа сервера (новый объект задачи с обновлённым completed)
			const updatedTodo = await updateTodo(id, { completed: newCompleted });

			// 2. Обновляем локальное состояние todos
			// setTodos с функциональным обновлением (prev => ...) - получает ТЕКУЩИЙ массив
			// prev - предыдущее значение состояния todos (актуальный массив задач)
			setTodos(
				(prev) =>
					// map проходит по КАЖДОЙ задаче в массиве и возвращает НОВЫЙ массив
					prev.map((todo) =>
						// Проверяем: если id текущей задачи (todo.id) === id обновляемой задачи
						todo.id === id
							? // ДА: заменяем задачу на updatedTodo (с сервера, с новым completed)
								updatedTodo
							: // НЕТ: оставляем задачу без изменений
								todo,
					), // map возвращает новый массив с одной заменённой задачей
			);

			// 3. Возвращаем обновлённую задачу наружу
			return updatedTodo;
		} catch (err) {
			// Если updateTodo выбросил ошибку (сервер недоступен, 404, 500...)
			// err содержит информацию: тип ошибки, текст, статус HTTP
			console.error('Ошибка при обновлении задачи:', err);
			// Логируем в консоль для отладки, НЕ ломает приложение
			// Пробрасываем ошибку дальше
			throw err;
		}
	};

	// Хук возвращает объект со всеми данными и функциями для работы с задачами
	return {
		// Массив всех задач с сервера
		todos,
		// Флаг загрузки (true = данные загружаются, false = загрузка завершена)
		isLoading,
		// Текст ошибки, если при загрузке произошла ошибка, или null, если всё ок
		error,
		// Функция для создания новой задачи
		createTodo: handleCreateTodo,
		// Функция для обновления задачи
		updateTodo: handleUpdateTodo,
		// Функция для удаления задачи
		deleteTodo: handleDeleteTodo,
		// Функция для переключения статуса "выполнено"
		toggleCompleted: handleToggleCompleted,
	};
};
