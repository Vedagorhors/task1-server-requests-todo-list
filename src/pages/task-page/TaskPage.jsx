import { useState } from 'react';
import { useParams, useNavigate } from 'react-router-dom'; // Хуки React Router для работы с URL и навигации
import styles from './TaskPage.module.css';
import { useTodos } from '../../hooks/useTodos';

export const TaskPage = () => {
	// Хук useTodos возвращает данные о задачах и функции для работы с ними
	// todos - полный массив всех задач с сервера (для поиска нужной задачи по id)
	// updateTodo - функция для обновления задачи на сервере
	// deleteTodo - функция для удаления задачи с сервера
	// toggleCompleted - функция для переключения статуса "выполнено" задачи
	const { todos, updateTodo, deleteTodo, toggleCompleted } = useTodos();

	// useParams() извлекает динамические параметры из URL /task/:id → возвращает объект { id: "1" }
	// :id - это динамический параметр в маршруте, который указывается в роутере как path="/task/:id"
	const { id } = useParams(); // id приходит строкой: "1", "2", "3"... (нужно будет привести к числу Number(id))

	// useNavigate() возвращает функцию для программной навигации (перехода между страницами)
	// Это полезно, когда нужно перейти на другую страницу не по клику на ссылку, а по какому-то событию (например, после удаления задачи)
	const navigate = useNavigate(); // navigate(-1) = назад на предыдущую страницу в истории браузера

	// Ищем задачу в массиве todos по id
	// Number(id) приводит строку "1" к числу 1 (потому что id в базе данных - это число)
	// .find() возвращает первый элемент массива, для которого коллбэк вернёт true
	const task = todos.find((t) => t.id === Number(id));

	// Локальное состояние для режима редактирования (НЕ синхронизируется с props или хуками)
	// false = режим просмотра задачи, true = режим редактирования текста задачи
	const [isEditing, setIsEditing] = useState(false);

	// Буфер для нового текста при редактировании (синхронизируется с input)
	// Инициализируется текущим названием задачи (task.title)
	// Если task не найден, будет ошибка, но ниже есть проверка if (!task) которая вернёт null вместо этого состояния
	const [editTitle, setEditTitle] = useState(task?.title || '');

	// Если задача не найдена (неверный id или удалена) — показываем сообщение об ошибке
	// Ранний возврат — не рендерим остальную разметку, чтобы избежать ошибок
	if (!task) {
		return <h1>Задача не найдена</h1>;
	}

	// Обработчик кнопки "Назад" — возвращает на предыдущую страницу (главную со списком)
	const handleBack = () => {
		// navigate(-1) - это команда браузеру "вернись на один шаг назад в истории"
		// Это как нажатие на кнопку "Назад" в браузере
		navigate(-1);
	};

	// Переключатель режима редактирования (просмотр ↔ редактирование)
	const handleEditToggle = () => {
		// Инвертируем значение isEditing: если было false → станет true, если было true → станет false
		setIsEditing(!isEditing);

		// Если ВКЛЮЧАЕМ редактирование (т.е. !isEditing === true, текущее значение было false)
		// то сбрасываем поле ввода на текущее название задачи
		if (!isEditing) {
			setEditTitle(task.title); // Берем актуальное название из объекта задачи
		}
	};

	// Сохранение изменений — отправляет обновление на сервер и выходит из режима редактирования
	const handleSave = () => {
		// Вызываем функцию updateTodo из хука useTodos для обновления задачи на сервере
		// updateTodo(task.id, { title: editTitle }) отправляет PATCH запрос на сервер:
		// - первый аргумент task.id - ID задачи, которую нужно обновить
		// - второй аргумент { title: editTitle } - объект с полями, которые нужно изменить
		updateTodo(task.id, { title: editTitle });

		// Выходим из режима редактирования (переключаем обратно в режим просмотра)
		setIsEditing(false);
	};

	// Удаление задачи с подтверждением пользователя
	const handleDelete = () => {
		// confirm() — нативный диалог браузера, показывающий сообщение с кнопками "ОК" и "Отмена"
		// Возвращает true, если пользователь нажал "ОК", и false, если "Отмена"
		if (confirm('Удалить задачу?')) {
			// Удаляем задачу через функцию deleteTodo из хука useTodos
			deleteTodo(task.id);

			// Сразу переходим на предыдущую страницу (назад в историю браузера)
			// Это нужно, чтобы пользователь не увидел пустую страницу удалённой задачи
			navigate(-1);
		}
	};

	return (
		// Основная разметка страницы задачи
		<main className={styles.taskPage}>
			{' '}
			{/* Кнопка "Назад" — всегда видна на странице */}
			<button onClick={handleBack} className={styles.backButton}>
				← На главную
			</button>
			{/* Заголовок задачи — всегда виден, показывает название задачи */}
			<h1>{task.title}</h1>
			{/* Чекбокс статуса "выполнено" — всегда виден, управляется состоянием completed с сервера */}
			<input
				type="checkbox"
				checked={task.completed} // Галочка ставится, если task.completed === true (данные с сервера)
				onChange={() => toggleCompleted(task.id, !task.completed)} // При клике переключает статус через функцию из хука
			/>
			{/* УСЛОВНАЯ ЛОГИКА: показываем либо режим редактирования, либо режим просмотра */}
			{isEditing ? ( // Тернарный оператор: условие ? true : false
				// РЕЖИМ РЕДАКТИРОВАНИЯ =============================================
				<>
					{/* Поле ввода с контролируемым значением */}
					<input
						value={editTitle} // Связанное с состоянием editTitle (управляется компонентом)
						onChange={(e) => setEditTitle(e.target.value)} // При вводе обновляет состояние editTitle
					/>

					{/* Кнопка сохранения — вызывает handleSave для отправки изменений на сервер */}
					<button onClick={handleSave}>Сохранить</button>

					{/* Кнопка отмены — возвращает в режим просмотра без сохранения */}
					<button onClick={handleEditToggle}>Отмена</button>
				</>
			) : (
				// ИНАЧЕ (режим просмотра)

				// РЕЖИМ ПРОСМОТРА ===================================================
				<>
					{/* Кнопка входа в режим редактирования — вызывает handleEditToggle */}
					<button onClick={handleEditToggle}>Редактировать</button>

					{/* Кнопка удаления — вызывает handleDelete для удаления задачи с сервера */}
					<button onClick={handleDelete}>Удалить</button>
				</>
			)}
		</main>
	);
};
