// Хук для фильтрации и сортировки списка задач
// Принимает объект с параметрами: todos (массив всех задач), search (поисковая фраза), sortAsc (направление сортировки)
export const useFilteredTodos = ({ todos, search, sortAsc }) => {
	// 1. Нормализуем поисковую фразу: убираем пробелы по краям и переводим в нижний регистр
	// Это нужно для корректного поиска без учета регистра и лишних пробелов
	// Например: "  КУПИТЬ ХЛЕБ  " превратится в "купить хлеб"
	const normalizedSearch = search.trim().toLowerCase();

	// 2. Создаем отфильтрованный и отсортированный список для отображения
	// Не мутируем исходный массив todos из пропов — работаем с его копией через методы filter и sort
	// todos — это все задачи из хука useTodos
	// visibleTodos — это уже отфильтрованные и отсортированные задачи, которые будут отображаться на странице
	const visibleTodos = todos
		// Шаг 2.1: ФИЛЬТРАЦИЯ по поисковой фразе
		// Метод filter() проходит по КАЖДОЙ задаче в массиве и возвращает НОВЫЙ массив
		// только с теми задачами, для которых коллбэк вернул true
		.filter((todo) => {
			// Если поисковая фраза пустая (пользователь ничего не ввёл) — показываем ВСЕ задачи
			if (!normalizedSearch) {
				// Возвращаем true = задача подходит, остаётся в списке
				return true;
			}

			// Иначе проверяем: содержит ли title задачи (в нижнем регистре) нашу поисковую фразу
			// .toLowerCase() - приводим заголовок задачи к нижнему регистру для поиска без учёта регистра
			// .includes(normalizedSearch) - проверяет, содержится ли фраза в заголовке
			// Например: "Купить молоко" и "молоко" → true, "Купить хлеб" и "молоко" → false
			return todo.title.toLowerCase().includes(normalizedSearch);
		})
		// Шаг 2.2: СОРТИРОВКА по алфавиту (после фильтрации)
		// Метод sort() сортирует массив МЕСТО, изменяя его (но мы уже создали новый массив через filter, так что ок)
		// Принимает коллбэк с двумя элементами (a и b) и возвращает:
		// - отрицательное число = a должно быть раньше b
		// - положительное число = b должно быть раньше a
		// - 0 = порядок не важен
		.sort((a, b) => {
			// Приводим заголовки обеих задач к нижнему регистру для корректной сортировки (русский/английский алфавит)
			const titleA = a.title.toLowerCase();
			const titleB = b.title.toLowerCase();

			// Проверяем направление сортировки
			if (sortAsc) {
				// Если sortAsc = true (сортировка A→Z: от А до Я)
				// localeCompare() сравнивает строки с учётом локали (правильно работает с русским алфавитом)
				// Возвращает отрицательное число, если titleA раньше titleB в алфавите
				return titleA.localeCompare(titleB);
			}

			// ИНАЧЕ (sortAsc = false: сортировка Z→A: от Я до А)
			// Меняем местами titleB и titleA для обратного порядка сортировки
			// Возвращает положительное число, если titleB раньше titleA в алфавите
			return titleB.localeCompare(titleA);
		});

	// 3. Возвращаем отфильтрованный и отсортированный массив задач
	// Этот массив будет использоваться для отображения на странице
	return visibleTodos;
};
